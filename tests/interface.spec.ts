import {expect,test} from '@playwright/test';
test('transport and live editing work through the interface; compositions round trip',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await page.getByTestId('diagnostics').click();
 await page.getByTestId('play').click();
 await expect(page.locator('.engine-status')).toHaveText('AUDIO READY');
 await expect(page.getByTestId('pause')).toBeEnabled();
 await expect.poll(async()=>JSON.parse(await page.locator('.diagnostics-content pre').innerText()).scheduled).toBeGreaterThan(4);
 await expect(page.getByRole('button',{name:'+ Add voice',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'linear',exact:true}).click();
 await expect(page.locator('.message.notice')).toContainText('Edit scheduled');
 await page.getByLabel('End tempo weight').fill('180');
 await page.getByLabel('End tempo weight').press('Tab');
 await expect(page.getByLabel('End tempo weight')).toHaveValue('180');
 await expect(page.getByRole('alert')).toHaveCount(0);
 await page.getByTestId('pause').click();
 await expect(page.getByTestId('play')).toBeEnabled();
 const paused=await page.getByLabel('Playback position').inputValue();
 await page.waitForTimeout(160);
 expect(await page.getByLabel('Playback position').inputValue()).toBe(paused);
 await page.getByTestId('play').click();
 await expect(page.getByTestId('pause')).toBeEnabled();
 await page.getByTestId('stop').click();
 await expect(page.getByLabel('Playback position')).toHaveValue('0');
 await page.getByLabel('Composition name').fill('Browser round trip');
 await page.getByLabel('Composition name').press('Tab');
 const downloadPromise=page.waitForEvent('download');
 await page.getByTestId('save').click();
 const download=await downloadPromise;const path=await download.path();expect(path).toBeTruthy();
 await page.getByLabel('Reset demo').click();
 await expect(page.getByLabel('Composition name')).toHaveValue('Divergence / 001');
 await page.getByTestId('load-composition').setInputFiles(path!);
 await expect(page.getByLabel('Composition name')).toHaveValue('Browser round trip');
 await expect(page.getByLabel('End tempo weight')).toHaveValue('180');
 await page.screenshot({path:testInfo.outputPath('confluence.png'),fullPage:true});
 expect(errors).toEqual([]);
});
test('mobile editor fits the viewport and malformed composition has a useful error',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByTestId('instrument-select').selectOption('bass');
 await expect(page.getByTestId('instrument-select')).toHaveValue('bass');
 await page.getByTestId('load-composition').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"name":"incomplete"}')});
 await expect(page.getByRole('alert')).toContainText('Invalid composition');
});
